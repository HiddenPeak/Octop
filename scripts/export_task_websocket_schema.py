"""Export the task WebSocket contract: uv run python scripts/export_task_websocket_schema.py."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from inhere_box.api.routers.project_tasks_ws import AuthenticateFrame, _command
from inhere_box.infra.agents.resident_history import (
    ResidentTimelineSnapshot,
    ResidentTimelineUpdate,
)
from inhere_box.infra.projects.artifact_models import (
    CreateArtifactArgs,
    PublishWorkspaceArchiveArgs,
    PublishWorkspaceFileArgs,
)
from inhere_box.infra.projects.client_tool_models import ClientToolCall, ClientToolClaim
from inhere_box.infra.projects.tasks import TaskDetail, TaskUpdate


def export_schema() -> dict[str, Any]:
    definitions: dict[str, Any] = {}

    def add(name: str, schema: dict[str, Any]) -> None:
        definitions.update(schema.pop("$defs", {}))
        definitions[name] = schema

    add("ClientCommand", _command.json_schema())
    for model in (
        AuthenticateFrame,
        TaskDetail,
        TaskUpdate,
        ResidentTimelineSnapshot,
        ResidentTimelineUpdate,
        ClientToolCall,
        ClientToolClaim,
        CreateArtifactArgs,
        PublishWorkspaceFileArgs,
        PublishWorkspaceArchiveArgs,
    ):
        add(model.__name__, model.model_json_schema())

    def ref(name: str) -> dict[str, str]:
        return {"$ref": f"#/$defs/{name}"}

    def event(
        name: str, kind: str, properties: dict[str, Any], optional: tuple[str, ...] = ()
    ) -> None:
        definitions[name] = {
            "type": "object",
            "properties": {"type": {"type": "string", "const": kind}, **properties},
            "required": ["type", *(key for key in properties if key not in optional)],
            "additionalProperties": True,
        }

    event(
        "ReadyEvent",
        "ready",
        {"protocol_version": {"type": "integer", "const": 3}, "session_replace": {"const": True}},
        optional=("session_replace",),
    )
    event(
        "ResultEvent",
        "result",
        {
            "id": {"type": "string", "pattern": "^[A-Za-z0-9_-]{8,128}$"},
            "data": {
                "anyOf": [
                    {"type": "null"},
                    ref("TaskDetail"),
                    ref("ClientToolCall"),
                    ref("ClientToolClaim"),
                ]
            },
        },
    )
    event("ApprovalPolicyEvent", "approval.policy", {"data": ref("TaskApprovalPolicy")})
    event("SnapshotEvent", "snapshot", {"data": ref("TaskDetail")})
    event("TurnEvent", "turn", {"data": ref("TaskUpdate")})
    event(
        "ResidentTimelineSnapshotEvent",
        "resident.timeline.snapshot",
        {"data": ref("ResidentTimelineSnapshot")},
    )
    event(
        "ResidentTimelineUpdateEvent",
        "resident.timeline.update",
        {"data": ref("ResidentTimelineUpdate")},
    )
    event("ToolCallEvent", "tool.call", {"data": ref("ClientToolCall")})
    event("ToolClosedEvent", "tool.closed", {"data": ref("ClientToolCall")})
    event(
        "ErrorEvent",
        "error",
        {
            "id": {"type": "string"},
            "task_id": {"type": "string"},
            "agent_id": {"type": "string"},
            "thread_id": {"type": "string"},
            "status": {"type": "integer", "minimum": 400, "maximum": 599},
            "error": {
                "type": "object",
                "properties": {
                    "code": {"type": "string"},
                    "message": {"type": "string"},
                    "details": {"type": "object"},
                },
                "required": ["code", "message", "details"],
            },
        },
        ("id", "task_id", "agent_id", "thread_id"),
    )
    event("SessionEvent", "session", {"access_token": {"type": "string", "minLength": 1}})
    event("HeartbeatEvent", "heartbeat", {})
    definitions["ServerEvent"] = {
        "oneOf": [ref(name) for name in definitions if name.endswith("Event")]
    }
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "inhere-box Conversation WebSocket Protocol 3",
        "description": "Authenticated task and resident subscriptions, task commands, durable client tools and server events for /api/project-tasks/ws.",
        "$comment": "Generated by scripts/export_task_websocket_schema.py. Read project-task-websocket.md for permissions, schema restrictions, ordering, idempotency and lifecycle rules.",
        "oneOf": [ref("AuthenticateFrame"), ref("ClientCommand"), ref("ServerEvent")],
        "$defs": definitions,
    }


if __name__ == "__main__":
    target = Path(__file__).resolve().parents[1] / "docs/project-task-websocket.schema.json"
    target.write_text(
        json.dumps(export_schema(), indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
